'use strict';
// Renders PRODUCTION-READINESS.md from a production-assurance report
// object. Every cell is computed from the JSON -- nothing in this file
// hand-types a PASS/FAIL/verdict for a specific run.

const fs = require('fs');

// Human-readable requirement label per result-name prefix. Falls back to
// the raw dotted name if a prefix isn't mapped here, so an unmapped new
// test still renders (just less prettily) instead of being silently
// dropped from the table.
const REQUIREMENT_LABELS = [
  [/^disaster-recovery\./, 'Backup/restore actually works'],
  [/^resilience\.container-loss\.recovery-time/, 'Failure recovery time'],
  [/^resilience\.container-loss\.detected/, 'Failure detection & alerting'],
  [/^security\.npm-audit\./, 'Dependency CVEs'],
  [/^security\.trivy\./, 'Container image CVEs'],
  [/^security\.gitleaks\./, 'Source secret exposure'],
  [/^security\.codeql\./, 'Source code vulnerabilities (static analysis)'],
  [/^load\.capacity\.mandatory/, 'Mandatory production capacity'],
  [/^load\.capacity\.breaking-point/, 'Load breaking point (informational)'],
  [/^fleet\.availability/, '23-device simultaneous ingestion availability'],
  [/^fleet\.integrity/, 'Ingestion data integrity (loss/dup/reorder)'],
  [/^data-quality\./, 'Data-correctness detection'],
];

function requirementFor(name) {
  for (const [re, label] of REQUIREMENT_LABELS) {
    if (re.test(name)) return label;
  }
  return name;
}

function nextActionFor(r) {
  if (r.status === 'PASS') return '-';
  if (r.status === 'NOT_TESTED') return 'run with a profile that includes this category';
  if (r.status === 'BLOCKED_EXTERNAL') return 'resolve the external blocker (see actual); re-run once resolved';
  if (r.status === 'BLOCKED_ENVIRONMENT') return 'fix local environment (tool/infra missing); re-run';
  if (r.status === 'BLOCKED_SCOPE') return 'intentionally withheld for safety; re-run with the required opt-in flag if this check is needed';
  if (r.status === 'WARN') return 'review approved risk exception / degraded-but-acceptable result';
  return 'investigate and fix -- see evidence';
}

function escapeCell(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function renderReadiness(report, outPath) {
  const lines = [];
  lines.push('<!-- GLOBAL_NAV -->');
  lines.push('<div align="right">');
  lines.push('  <a href="README.md"><img src="docs/assets/icons/home.svg" width="16" align="center" /> <b>Home</b></a> &nbsp;|&nbsp;');
  lines.push('  <a href="docs/README.md"><img src="docs/assets/icons/book.svg" width="16" align="center" /> <b>Docs Index</b></a>');
  lines.push('</div>');
  lines.push('<br/>');
  lines.push('');
  lines.push('# Production Readiness');
  lines.push('');
  lines.push('Generated by `scripts/production-assurance.js` -- every cell below is computed from a real run\'s');
  lines.push('machine-readable results (`docs/evidence/runtime/production-assurance-*.json`), never hand-typed.');
  lines.push('The verdict is `scripts/gate.js`\'s pure function over that JSON, not an assertion.');
  lines.push('');
  lines.push(`**Profile run:** \`${report.profile}\`  `);
  lines.push(`**Timestamp:** ${report.timestamp}  `);
  lines.push(`**Profile verdict:** **${report.verdict}**`);
  lines.push('');
  lines.push(
    `> **This is a \`${report.profile}\`-profile verdict, not a whole-system readiness claim.**` +
      ' **Profile GO** means every *blocking* requirement that this profile\'s own category list actually ran' +
      ' passed -- categories outside that list report `NOT_TESTED` below and are excluded from this verdict by' +
      ' design, not silently assumed passing. **Whole-system production readiness** is only ever established by' +
      ' running the `full` profile (the only one that exercises every category in `scripts/production-assurance.js`\'s' +
      ' `PROFILES`) -- a `fast` (or any non-`full`) GO must never be read or reported as "production ready".'
  );
  lines.push('');
  if (report.reasons && report.reasons.length) {
    lines.push('**Reasons:**');
    for (const reason of report.reasons) lines.push(`- ${reason}`);
    lines.push('');
  }

  lines.push('| Requirement | Test | Threshold | Evidence | Result | Blocking | Next Action |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const r of report.results) {
    lines.push(
      `| ${escapeCell(requirementFor(r.name))} | ${escapeCell(r.name)} | ${escapeCell(r.threshold)} | ${escapeCell(r.evidence)} | ${r.status} | ${r.blocking ? 'yes' : 'no'} | ${escapeCell(nextActionFor(r))} |`
    );
  }
  lines.push('');
  lines.push(
    `A profile only exercises its own category list (see \`scripts/production-assurance.js\`'s \`PROFILES\`) --` +
      ' a category not run this time shows as `NOT_TESTED` above and does not affect this run\'s verdict.' +
      ' Only a `full` profile run claims whole-system readiness.'
  );
  lines.push('');

  fs.writeFileSync(outPath, lines.join('\n'));
}

module.exports = { renderReadiness, requirementFor, nextActionFor };
