#!/usr/bin/env node
/**
 * Recovers the Floor 1 equipment records excluded from floor1-geometry.json
 * because their CAD INSERT's own insertion point falls outside the building
 * envelope while the geometry they draw is inside it.
 *
 * WHY THIS EXISTS
 * ----------------
 * extract-floor1-equipment.js positions a machine at its INSERT's insertion
 * point (deliberately -- see that file's own comments) and filters the
 * census to entries whose insertion point falls inside the envelope
 * (`inWindow`, extract-floor1-equipment.js:515). 68 machines in this
 * drawing -- including the complete 8x5 grid that is the EAP operational
 * map's 40 DIRECT cells -- draw their body inside the envelope from an
 * insertion point placed outside it, so that filter silently excludes them.
 * They are real, drawn, on the same "00.Machine" layer as the rest -- not
 * an extraction bug, a documented and load-bearing filtering choice
 * (commit 8f6a6e5: "the equipment pipeline filters on the insertion point
 * and therefore misses them; recorded here, not fixed here").
 *
 * WHAT THIS DOES NOT DO
 * -----------------------
 * It does not re-parse the DXF and does not re-derive a drawn-geometry
 * position from scratch. floor1-machine-nodes.json already computed exactly
 * that position, by its own documented method ("placed by their own drawn
 * geometry rather than by their insertion point" -- commit 8f6a6e5). Two
 * independent re-derivations of the same number is not a safety margin, it
 * is a second guess; this borrows the one that already exists and passes it
 * through the SAME canonical transform (lib/floor1-frame.js) every other
 * position in this pipeline goes through, never a new one.
 *
 * It does not touch scripts/extract-floor1-equipment.js, its filter, or any
 * existing equipment record. Every existing id, position, rotation,
 * footprint and zone assignment is untouched -- this is an ADDITIVE pass
 * only, run after that script, never a modification of it. Existing ids are
 * positional over that script's own filtered iteration order (see its
 * comments at the id-assignment site); looping the recovered population
 * back INTO that filter and re-running it would renumber existing machines,
 * because the recovered population is interspersed through the DXF's
 * native order, not appended at the end. This script exists specifically
 * so that never has to happen: new ids are allocated by this script alone,
 * continuing from the current maximum, and the two numbering spaces never
 * collide because they are never generated by the same pass.
 *
 * It does not assign an IMS machine_id, a zone from the EAP layout image,
 * or a footprint polygon this drawing did not measure this way. Every field
 * this script cannot honestly populate is left null, exactly as the
 * existing 344 records leave a field null when they lack the evidence for
 * it -- never filled with a plausible-looking default.
 *
 * OUTPUT
 * -------
 * Writes NOTHING by default. Prints the recovered records and a diff
 * summary to stdout. Pass --write <path> to write the merged document to a
 * file (a candidate path, never the live private/floor1-geometry.json
 * unless explicitly told to via that argument) -- this script never
 * discovers or overwrites the production file on its own.
 *
 * Usage:
 *   node scripts/recover-floor1-outside-envelope-equipment.js
 *   node scripts/recover-floor1-outside-envelope-equipment.js --write <output.json>
 *   FACTORY_TWIN_PRIVATE_DIR=<dir> node scripts/recover-floor1-outside-envelope-equipment.js
 */

'use strict';

const fs = require('fs');
const path = require('path');
const frame = require('./lib/floor1-frame');
const B = require('./lib/cad-blocks');

const PRIVATE_DIR = process.env.FACTORY_TWIN_PRIVATE_DIR
  || path.join(__dirname, '..', 'services', 'factory-twin-3d', 'private');

const GEOMETRY_PATH = path.join(PRIVATE_DIR, 'floor1-geometry.json');
const NODES_PATH = path.join(PRIVATE_DIR, 'floor1-machine-nodes.json');
const ZONES_PATH = path.join(PRIVATE_DIR, 'floor1-zones.json');

function readJson(p) {
  if (!fs.existsSync(p)) {
    console.error(`missing required input: ${p}`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

/** Whether a census node's own insertion point falls outside the envelope. */
function insertionOutside(node, widthMm, depthMm) {
  const x = node.insertion_x_mm;
  const y = node.insertion_y_mm;
  if (typeof x !== 'number' || typeof y !== 'number') return null;
  return x < 0 || x > widthMm || y < 0 || y > depthMm;
}

function loadZones(zonesPath) {
  if (!fs.existsSync(zonesPath)) return [];
  const doc = JSON.parse(fs.readFileSync(zonesPath, 'utf8'));
  const list = Array.isArray(doc.functional_zones) ? doc.functional_zones
    : (Array.isArray(doc.zones) ? doc.zones : []);
  return list.map((z) => ({
    id: z.id,
    poly: ((z.geometry && z.geometry.vertices) || []).map((v) => [v.x, v.z]),
  })).filter((z) => z.poly.length >= 3);
}

/**
 * The exact production zone rule (extract-floor1-equipment.js:901-912),
 * reused verbatim via lib/cad-blocks -- never reimplemented. `.find()`, not
 * `.filter()`: production has no multi-zone detection, so neither does this.
 */
function assignZone(position, footprint, rotationDeg, zones) {
  const hit = zones.find((z) => B.pointInPolygon(position.x, position.z, z.poly));
  if (!hit) return { zone_id: null, zone_status: 'OUTSIDE_ROOM' };
  if (!footprint) return { zone_id: hit.id, zone_status: 'ROOM_BY_CENTRE_ONLY' };
  const shape = B.twinBoxCorners(position.x, position.z, footprint.width, footprint.depth, rotationDeg);
  const allIn = shape.every(([px, pz]) => B.pointInPolygon(px, pz, hit.poly));
  return { zone_id: hit.id, zone_status: allIn ? 'INSIDE_ROOM' : 'CROSSES_ROOM_BOUNDARY' };
}

function main() {
  const writeIdx = process.argv.indexOf('--write');
  const writePath = writeIdx >= 0 ? process.argv[writeIdx + 1] : null;

  const geo = readJson(GEOMETRY_PATH);
  const nodesDoc = readJson(NODES_PATH);
  const nodes = nodesDoc.machine_nodes || [];
  const zones = loadZones(ZONES_PATH);

  const widthMm = geo.envelope.width * 1000;
  const depthMm = geo.envelope.depth * 1000;
  const halfW = geo.envelope.width / 2;
  const halfD = geo.envelope.depth / 2;

  const existingHandles = new Set(geo.equipment.map((e) => e.cad_source_handle));
  const existingIds = new Set(geo.equipment.map((e) => e.id));
  const maxSeq = geo.equipment.reduce((max, e) => {
    const n = parseInt(String(e.id).replace('EQP-F1-', ''), 10);
    return Number.isFinite(n) && n > max ? n : max;
  }, 0);

  const recovered = [];
  const skipped = { alreadyPresent: 0, noPosition: 0 };
  let nextSeq = maxSeq + 1;

  for (const node of nodes) {
    if (insertionOutside(node, widthMm, depthMm) !== true) continue;
    if (existingHandles.has(node.cad_handle)) { skipped.alreadyPresent += 1; continue; }
    if (typeof node.x_mm !== 'number' || typeof node.y_mm !== 'number') {
      skipped.noPosition += 1; continue;
    }

    const x = round3(frame.cadXToTwin(node.x_mm, halfW));
    const z = round3(frame.cadYToTwin(node.y_mm, halfD));
    const rotation_deg = frame.cadRotationToTwinDegrees(node.rotation_deg || 0);
    const hasFootprint = typeof node.width_mm === 'number' && typeof node.depth_mm === 'number';
    const footprint = hasFootprint
      ? { width: round3(node.width_mm / 1000), depth: round3(node.depth_mm / 1000) }
      : null;

    const id = `EQP-F1-${String(nextSeq).padStart(4, '0')}`;
    if (existingIds.has(id)) {
      // Cannot happen given maxSeq is the true current maximum, but a
      // collision here is exactly the failure this script exists to avoid,
      // so it is a hard stop rather than a skipped record.
      console.error(`FATAL: generated id ${id} already exists. Aborting, nothing written.`);
      process.exit(1);
    }
    nextSeq += 1;

    const zoneInfo = assignZone({ x, z }, footprint, rotation_deg, zones);

    recovered.push({
      id,
      cad_equipment_id: id,
      position: { x, y: 0, z },
      // No insertion point is recorded: it is, by construction, the exact
      // value that put this record outside the primary pipeline's window,
      // and repeating it here would invite a future filter to exclude it
      // again for the same reason.
      insertion_point: null,
      rotation_deg,
      rotation_source: 'cad_insert_rotation',
      mirrored: node.mirrored === true,
      scale: { x: typeof node.scale_x === 'number' ? node.scale_x : 1, y: 1, z: typeof node.scale_y === 'number' ? node.scale_y : 1 },
      geometry_status: hasFootprint ? 'MEASURED_CAD' : 'UNRESOLVED',
      footprint,
      footprint_status: hasFootprint ? 'MEASURED_CAD' : 'UNRESOLVED',
      footprint_source: hasFootprint ? 'cad_block_geometry' : null,
      footprint_shape: hasFootprint ? 'rectangle' : 'unresolved',
      // No polygon: the census recorded a drawn-extent bounding size, not a
      // vertex outline. Carrying a fabricated rectangle-as-polygon here
      // would claim a measurement this pass does not have.
      footprint_polygon: null,
      footprint_polygon_area_m2: null,
      display_shape: hasFootprint ? 'OPERATIONAL_RECTANGLE' : 'UNRESOLVED',
      display_vertices: hasFootprint ? 4 : null,
      // No measured polygon exists to compare the rectangle against (the
      // census recorded a drawn-extent size, not an outline), so there is
      // no discrepancy to report: the rectangle IS the whole measurement,
      // not an approximation of a finer one. 0, not null -- the validator
      // (tests/lint/floor1-geometry-validator.js) requires a real number
      // here whenever a footprint is claimed, the same rule every existing
      // record with a footprint already satisfies.
      display_area_error: hasFootprint ? 0 : null,
      display_source: hasFootprint ? 'filtered_physical_footprint' : null,
      operational_footprint: hasFootprint
        ? { width: footprint.width, depth: footprint.depth, offset_x: 0, offset_z: 0 }
        : null,
      operational_axis_offset_deg: hasFootprint ? 0 : null,
      orientation_geometry_mismatch: false,
      operational_excludes_enclosure: false,
      footprint_hull_vertices: null,
      footprint_fill: null,
      footprint_note: 'RECOVERED: position borrowed from floor1-machine-nodes.json '
        + '(drawn-geometry method), not re-measured by this pass. See '
        + 'docs/eap-floor1-spatial-registration.md and commit 8f6a6e5.',
      unresolved_reason: hasFootprint ? null : 'NO_DRAWN_EXTENT_IN_CENSUS',
      measurement: null,
      confidence: typeof node.confidence === 'string' ? node.confidence.toLowerCase() : 'medium',
      source: 'floor1_dxf',
      cad_layer: node.layer || null,
      cad_block: node.block_name || null,
      cad_block_name: node.block_name || null,
      cad_source_handle: node.cad_handle,
      family_size: 1,
      zone_id: zoneInfo.zone_id,
      zone_status: zoneInfo.zone_status,
      // Identity is a separate question from geometry and is never inferred
      // from either. Nothing here maps a machine to IMS -- and even if this
      // field claimed otherwise, the server derives ims_device_id from
      // floor1-asset-mapping.json alone (lib/wire.js's deviceIdFor), never
      // from this record's own say-so.
      ims_machine_id: null,
      ims_device_id: null,
      mapping_status: 'UNMAPPED_TO_IMS',
      status: 'UNMAPPED',
      height_status: 'unknown',
      outside_envelope: false,
      envelope_overhang_m: 0,
      footprint_overlaps_neighbour: false, // not independently re-verified by this pass
    });
  }

  const recoveredWithFootprint = recovered.filter((r) => r.footprint !== null).length;
  const recoveredUnresolved = recovered.length - recoveredWithFootprint;
  const baseCounts = (geo.equipment_extraction && geo.equipment_extraction.counts) || {};

  const merged = {
    ...geo,
    equipment: [...geo.equipment, ...recovered],
    equipment_extraction: {
      ...geo.equipment_extraction,
      counts: {
        ...baseCounts,
        candidates: geo.equipment.length + recovered.length,
        footprint_resolved: (baseCounts.footprint_resolved || 0) + recoveredWithFootprint,
        footprint_unresolved: (baseCounts.footprint_unresolved || 0) + recoveredUnresolved,
      },
      recovery_pass_note: `${recovered.length} additional records appended by `
        + 'scripts/recover-floor1-outside-envelope-equipment.js: insertion-point-'
        + 'outside-envelope population, position borrowed from floor1-machine-nodes.json. '
        + 'The original candidates count and method above describe the primary pass only.',
    },
  };

  console.log(`Existing equipment: ${geo.equipment.length}`);
  console.log(`Census nodes: ${nodes.length}`);
  console.log(`Recovered: ${recovered.length}`);
  console.log(`Skipped (already present): ${skipped.alreadyPresent}`);
  console.log(`Skipped (no drawn-extent position): ${skipped.noPosition}`);
  console.log(`Merged total: ${merged.equipment.length}`);

  const allHandles = merged.equipment.map((e) => e.cad_source_handle);
  const dupHandles = allHandles.filter((h, i) => allHandles.indexOf(h) !== i);
  const allIds = merged.equipment.map((e) => e.id);
  const dupIds = allIds.filter((id, i) => allIds.indexOf(id) !== i);
  console.log(`Duplicate handles: ${dupHandles.length}`);
  console.log(`Duplicate ids: ${dupIds.length}`);
  if (dupHandles.length || dupIds.length) {
    console.error('FATAL: duplicates detected. Nothing written.');
    process.exit(1);
  }

  if (writePath) {
    fs.writeFileSync(writePath, JSON.stringify(merged, null, 2));
    console.log(`Written: ${writePath}`);
  } else {
    console.log('No --write path given: dry run only, nothing written.');
  }
}

function round3(v) { return Math.round(v * 1000) / 1000; }

main();
