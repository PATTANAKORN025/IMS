-- Machine registry: the factory each drilling machine belongs to (Fleet
-- Overview label and factory filter). Same definition as migration 089.
CREATE TABLE IF NOT EXISTS public.machine_master (
    equipment_id VARCHAR(100) NOT NULL,
    brand        VARCHAR(50),
    model        VARCHAR(50),
    factory      VARCHAR(5),
    CONSTRAINT pk_machine_master PRIMARY KEY (equipment_id)
);

-- ---------------------------------------------------------------- vcp
-- One row per line per minute. 18 rectifier stations, two sides (a/b) each;
-- 18 pumps; nine baths. The source swaps the bath tags: preset_<bath> is the
-- reading and actual_<bath> the setpoint (see migration 086, vcp.upp).
DO $$
DECLARE
    cols text := '';
    bath text;
    i int;
BEGIN
    IF to_regclass('public.vcp_upp') IS NOT NULL THEN
        RETURN;
    END IF;
    FOREACH bath IN ARRAY ARRAY['clean','copperplating1','copperplating2','ao','hotwater','dry','heating','peeloff','rectifier'] LOOP
        cols := cols || format(', actual_%s numeric, preset_%s numeric', bath, bath);
    END LOOP;
    FOR i IN 1..18 LOOP
        cols := cols || format(', actual_current_%sa numeric, actual_current_%sb numeric', i, i)
                     || format(', preset_current_%sa numeric, preset_current_%sb numeric', i, i)
                     || format(', actual_voltage_%sa numeric, actual_voltage_%sb numeric', i, i)
                     || format(', actual_pump_%s numeric, preset_pump_%s numeric', i, i)
                     || format(', preset_amp_%sa numeric', i);
        -- the source table has no preset_amp_15b column; keep the shape
        IF i <> 15 THEN
            cols := cols || format(', preset_amp_%sb numeric', i);
        END IF;
    END LOOP;
    EXECUTE 'CREATE TABLE public.vcp_upp (
        log_id text NOT NULL,
        log_date timestamptz NOT NULL,
        trx_id text,
        jobkey text,
        equipment_id text,
        factory text,
        "timestamp" text,
        waveform text,
        line_speed numeric,
        plating_time numeric,
        density numeric,
        thickness numeric,
        width numeric,
        height numeric,
        plating_area_a numeric,
        plating_area_b numeric,
        copper_a_preset_current numeric,
        copper_b_preset_current numeric,
        current_check text,
        frequency_check text,
        pump_frequency numeric,
        actual_frequency_1 numeric,
        preset_frequency_1 numeric,
        shielding_board numeric,
        actual_shielding_board numeric,
        preset_shielding_board numeric,
        copper_thick_low numeric,
        copper_thick_high numeric,
        actual_tank numeric,
        preset_tank numeric,
        actual_amp_1a numeric,
        actual_amp_1b numeric,
        actual_prep numeric,
        pre_clean numeric,
        preset_cleaning_temp numeric,
        actual_cleaning_temp numeric' || cols || ')';
END
$$;
SELECT create_hypertable('public.vcp_upp', 'log_date', chunk_time_interval => INTERVAL '7 days', if_not_exists => true);
CREATE INDEX IF NOT EXISTS ix_mock_vcp_upp_eqp_time ON public.vcp_upp (equipment_id, log_date DESC);

