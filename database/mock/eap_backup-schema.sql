-- ============================================================================
-- Synthetic eap_backup schema for development, CI and demos.
--
-- The production eap_backup database is a restore of plant data and is not in
-- git. This file creates the subset of it that the drilling and VCP dashboards,
-- the VCP alert rules and migrations 084-086 read, so that the whole path can
-- run on generated data (scripts/mock/eap-mock-data.js) with no factory data.
--
-- Column names and the table/view split follow the objects the dashboards
-- query. Column types are reconstructed from how the dashboards and
-- migrations use each column; they are not a dump of the plant server.
--
-- Safety: this file refuses to run on a database that already holds these
-- tables without the public.mock_dataset marker, so it cannot be pointed at a
-- restored plant database by mistake. It is idempotent on a mock database.
--
-- Usage (inside the TimescaleDB container or any psql client):
--   psql -v ON_ERROR_STOP=1 -d eap_backup -f database/mock/eap_backup-schema.sql
-- ============================================================================

DO $$
BEGIN
    IF to_regclass('public.mock_dataset') IS NULL
       AND (to_regclass('public.machine_event') IS NOT NULL
            OR to_regclass('public.vcp_upp') IS NOT NULL) THEN
        RAISE EXCEPTION 'refusing to run: % already holds machine_event/vcp_upp and is not a mock database (no public.mock_dataset)', current_database();
    END IF;
END
$$;

CREATE EXTENSION IF NOT EXISTS timescaledb;

-- Marker: every row the generator writes is traceable to one run.
CREATE TABLE IF NOT EXISTS public.mock_dataset (
    run_id       text PRIMARY KEY,
    generated_at timestamptz NOT NULL DEFAULT now(),
    seed         bigint NOT NULL,
    hours        numeric NOT NULL,
    generator    text NOT NULL
);
COMMENT ON TABLE public.mock_dataset IS 'Marks this database as synthetic. One row per generator run. Created by database/mock/eap_backup-schema.sql.';

