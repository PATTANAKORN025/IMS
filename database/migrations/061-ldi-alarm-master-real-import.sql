-- ══════════════════════════════════════════════════════════════
-- Replaces the 20-row mock alarm master (migration 036) with the real
-- vendor error code list (source: "Machine error code list20250723",
-- provided 2026-08-07) -- 1,820 rows, columns AlarmId/AlarmType/
-- AlarmCode/AlarmMsg/AlarmDetail map 1:1 onto this table's existing
-- columns. One source row (AlarmId 011A0001) has a corrupted AlarmMsg
-- (an unescaped leading quote in the source spreadsheet swallowed the
-- rest of the file when parsed as CSV/TSV) -- kept as the literal
-- fragment left in the source rather than inventing a replacement.
-- 1,297 rows had the literal string "NULL" in AlarmDetail (a human
-- typed the word, not an actual NULL) -- converted to real NULL.
--
-- severity: new column, ISA-18.2-style Critical/Major/Minor/Warning,
-- computed with a documented, auditable rule (not vendor-sourced --
-- no severity field exists in the source list):
--   1. message matches a safety/hard-fault keyword regex (emergency,
--      e-stop, crash, collision, overcurrent, fire, critical, safety,
--      violation, overheat, speeding, hyper-acceleration) -> Critical,
--      regardless of AlarmType.
--   2. else AlarmType = 'E' -> Critical (all 23 are motion/servo safety
--      faults per direct inspection: HomeError, Overcurrent, Emergency
--      Stop, Critical position error, etc.)
--   3. else AlarmType = 'W' -> Warning (workflow/MES/config advisories)
--   4. else AlarmType = 'A' (the bulk, 1,595 rows): Minor if the message
--      contains a softer/procedural keyword (timeout, retry, not
--      supported, empty, invalid, parameter, please, not found) that
--      typically indicates a recoverable/retryable condition, else
--      Major (hard functional failure blocking production).
-- Live breakdown: {'Critical': 43, 'Major': 1431, 'Minor': 145, 'Warning': 201}

